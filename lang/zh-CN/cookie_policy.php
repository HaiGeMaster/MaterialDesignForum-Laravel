## 二、什么是 Cookie 及类似技术

Cookie 是网站存放在您设备（电脑、手机、平板等）上的小型文本文件。当您再次访问时，网站可以读取这些文件，从而识别您的浏览器、记住您的设置，或了解您的访问行为。

除 Cookie 外，我们所说的"Cookie 及类似技术"还包括：

- **像素 / 网络信标（Web Beacon）**：嵌入页面或邮件中的微小图像，在被加载时向服务器回传信息
- **本地存储与会话存储（localStorage / sessionStorage）**：浏览器提供的本地数据存储机制，容量大于 Cookie
- **SDK**：移动应用中用于数据采集与功能实现的软件开发工具包
- **设备指纹脚本**：通过采集设备属性识别回访用户，不在设备上存储数据

按设置方可分为**第一方 Cookie**（由本网站域名设置）与**第三方 Cookie**（由外部服务方设置）；按时效可分为**会话 Cookie**（关闭浏览器即删除）与**持久 Cookie**（在设定的存续期内保留）。

