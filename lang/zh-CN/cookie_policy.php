## 六、如何管理您的 Cookie 偏好

### 6.1 通过我们的同意工具

首次访问本网站时，我们会以底部横幅的形式征求您的意见，您有三个同等便捷的选择：

- **全部接受**：启用所有类别的 Cookie
- **全部拒绝**：仅启用必要类 Cookie
- **自定义分类**：打开偏好中心，逐类查看 Cookie 明细表并分别开启或关闭

在偏好中心中，您可以展开每个类别，查看该类别下每一条 Cookie 的名称、提供方、目的、类型与存续期。

### 6.2 随时更改或撤回

您可以**随时**通过以下任一方式更改或撤回您的同意，其便捷程度与作出同意时相同：

- 点击网站页脚的「Cookie 设置」链接
- 点击页面右下角的 Cookie 设置按钮

撤回同意后，我们将立即停止相应类别的脚本加载，并删除已写入您设备的相关 Cookie（第三方域名下的 Cookie 需由服务方清除，我们将同步通知其处理）。

**拒绝或撤回同意不会影响您正常使用本网站的基本功能**，我们不会以此为由拒绝提供服务。

### 6.3 通过浏览器设置

您也可以直接通过浏览器管理 Cookie——包括阻止所有 Cookie、仅阻止第三方 Cookie，或在关闭浏览器时自动清除。各主流浏览器的设置入口如下：

- Chrome：设置 → 隐私和安全 → Cookie 及其他网站数据
- Firefox：设置 → 隐私与安全 → Cookie 和网站数据
- Safari：设置 → 隐私 → 管理网站数据
- Edge：设置 → Cookie 和网站权限 → 管理和删除 Cookie

请注意：如您通过浏览器阻止必要类 Cookie，本网站的登录、会话维持等核心功能可能无法正常使用。

